import { authenticateCodexSummaryEdits } from './codex-comment-edit.mjs';
/** Protected-main ONLY: independently fetch authenticated source, model, CI and
 * owner evidence, write model-only Graph events with trusted Graph Harness, and
 * generate a sealed v3 receipt bundle. PR files are inert, never executed.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { reviewedSourceDigest, verifyReview } from './review-gate.mjs';
import { signApproval, verifyApprovalSignature } from './approval-signature.mjs';
import { obtainProtectedGraniteReview } from './protected-granite-artifact.mjs';
import { authenticateOwnerAuthorization } from './solo-release-provenance.mjs';
import { validateQualityRun, ghPages, authenticateIndependentSourceReview } from './trusted-attestor.mjs';
import { invariant } from './policy.mjs';

const ROOT = resolve(import.meta.dirname,'../..');
const REPO = 'BernydotJar/LUMA';
const sha = file => createHash('sha256').update(readFileSync(file)).digest('hex');
const gh = url => JSON.parse(execFileSync('gh',['api',url],{
  encoding:'utf8',timeout:30000,maxBuffer:12*1024*1024 }));
const git = (cwd,...args) => execFileSync('git',args,{cwd,encoding:'utf8',timeout:20000}).trim();
const DIGEST=/^[a-f0-9]{64}$/;
function save(dir,name,value) {
  const path=resolve(dir,'evidence/cicd-enterprise',name);
  writeFileSync(path,JSON.stringify(value,null,2)+'\n');
  return sha(path);
}

export async function signProtectedSoloRelease({ directory,prNumber,ciRunId }) {
  invariant(process.env.GITHUB_ACTIONS==='true' &&
    process.env.GITHUB_REF==='refs/heads/main' &&
    process.env.GITHUB_EVENT_NAME==='workflow_dispatch' &&
    process.env.GITHUB_REPOSITORY===REPO,
    'Solo release signing must run on protected main');
  invariant(Number.isSafeInteger(prNumber) && prNumber>0 &&
    Number.isSafeInteger(ciRunId) && ciRunId>0,
    'Exact PR number and QA run are mandatory');
  const protectedSha=git(ROOT,'rev-parse','HEAD');
  invariant(protectedSha===process.env.GITHUB_SHA,
    'Protected signing policy source differs from the GitHub Actions SHA');
  const graphRoot=resolve(process.env.GRAPH_HARNESS_ROOT || '');
  const trustedGraph=git(graphRoot,'rev-parse','HEAD');
  invariant(trustedGraph==='f8bb28ec0933f54df5ff2e0d2c06a731471ec47e',
    'Graph runtime is not the approved immutable revision');
  const pr=gh(`repos/${REPO}/pulls/${prNumber}`);
  const head=git(directory,'rev-parse','HEAD');
  invariant(pr?.head?.sha===head && pr.head.repo?.full_name===REPO &&
    pr.base?.ref==='main' && pr.state==='open' && !pr.merged,
    'PR exact source or trust boundaries changed');
  const source=reviewedSourceDigest(directory);
  invariant(DIGEST.test(source),'Reviewed source digest invalid');
  const quality=gh(`repos/${REPO}/actions/runs/${ciRunId}`);
  const jobs=gh(`repos/${REPO}/actions/runs/${ciRunId}/jobs?filter=latest&per_page=100`).jobs;
  const registry=gh(`repos/${REPO}/actions/workflows/quality.yml`);
  validateQualityRun(quality,jobs,head,registry.id);
  const model=await obtainProtectedGraniteReview({prNumber,reviewedCommit:head,
    sourceDigest:source,trustedModelDigest:process.env.LUMA_GRANITE_MODEL_DIGEST});
  invariant(model.run.head_sha===protectedSha,
    'Model audit was generated by a superseded protected policy revision');
  const scope=model.report.riskClassification==='public-landing'
    ? 'public-landing':'owner-risk-exception';
  const comments=authenticateCodexSummaryEdits(ghPages(`repos/${REPO}/issues/${prNumber}/comments?per_page=100`));
  const owner=authenticateOwnerAuthorization(comments,head,model.run.updated_at,scope);
  const modelVerdict=model.provenance.verdict;
  invariant(['PASS','NEEDS_REVIEW'].includes(modelVerdict),
    'Protected model review is incomplete or unverifiable');
  const findings=model.report.result?.findings ?? [];
  invariant(findings.length===0,
    'The model classifier must not invent ungrounded source findings');
  let codexReviewCommentId=0;
  if(modelVerdict==='NEEDS_REVIEW'){
    invariant(scope==='public-landing',
      'Only public-only changes may use a Codex+owner adjudication of Granite uncertainty');
    const reviews=ghPages(`repos/${REPO}/pulls/${prNumber}/reviews?per_page=100`);
    const commits=ghPages(`repos/${REPO}/pulls/${prNumber}/commits?per_page=100`);
    const contributors=commits.flatMap(c=>[c.author?.login,c.committer?.login].filter(Boolean));
    const codex=authenticateIndependentSourceReview(comments,reviews,head,pr.user.login,
      process.env.LUMA_RELEASE_TRUSTED_REVIEWERS,contributors);
    invariant(codex.method==='github-codex-clean-review' && codex.reviewer===
      'chatgpt-codex-connector[bot]' && codex.reviewId>0,
      'Authenticated exact-source clean Codex receipt required to adjudicate model warning');
    codexReviewCommentId=codex.reviewId;
  }
  const critic = { schemaVersion:3, model:'ibm/granite3.3:2b',complete:true,
    reviewerType:'automated-model-critic',humanIndependent:false,
    reviewedSourceDigest:source,reviewedCommit:head,
    sourceSha256:model.report.inputSha256,
    authenticatedProtectedRunId:model.run.id,
    authenticatedArtifactSha256:model.provenance.artifactDigestSha256,
    trustedWorkflowCommit:protectedSha,
    modelDigest:model.provenance.modelDigest,
    evaluation:{verdict:modelVerdict,findings,limitations:model.report.result?.limitations||[]},
    adjudication:{needed:modelVerdict==='NEEDS_REVIEW',
      codexReviewCommentId,ownerCommentId:owner.commentId,sourceSha:head,
      note:'Advisory Granite warning accepted only after authenticated clean Codex and sole-owner risk approval'},
  };
  const verifier = { schemaVersion:3,status:'PASS',reviewedSourceDigest:source,
    reviewedCommit:head,unresolvedCritical:0,unresolvedHigh:0,dispositions:[],
    reviewerType:'deterministic-protected-source-verifier',humanIndependent:false,
    modelWorkflowRunId:model.run.id,modelArtifactSha256:model.provenance.artifactDigestSha256,
    modelDigest:model.provenance.modelDigest,ownerCommentId:owner.commentId,
    modelVerdict,codexReviewCommentId,
    ciRunId:quality.id,verifiedChecks:jobs.filter(j=>j.conclusion==='success').map(j=>j.name),
  };
  const ci={schemaVersion:3,status:'TECHNICAL_GATES_PASS_RELEASE_PENDING',
    reviewedSourceDigest:source,testedCommit:head,runId:quality.id,
    githubWorkflowId:registry.id,githubRunConclusion:quality.conclusion,
    qualityJobs:jobs.map(j=>({name:j.name,conclusion:j.conclusion})),
  };
  const criticHash=save(directory,'granite-review.json',critic);
  const verifierHash=save(directory,'independent-review.json',verifier);
  const ciHash=save(directory,'release-ci.json',ci);
  const graph=JSON.parse(execFileSync('python3',[
    resolve(ROOT,'scripts/release/record-solo-graph.py'),
    '--candidate',directory,'--source-digest',source,'--source-commit',head,
    '--ci-run-id',String(ciRunId),'--model-run-id',String(model.run.id),
    '--owner-comment-id',String(owner.commentId),
    '--model-verdict',modelVerdict,'--codex-comment-id',String(codexReviewCommentId),
  ],{ cwd:ROOT,encoding:'utf8',timeout:90000,
    env:{...process.env,GRAPH_HARNESS_ROOT:graphRoot},maxBuffer:1024*1024 }));
  invariant(graph?.status==='PASS' && graph.graphEventHash &&
    graph.criticSha256===criticHash && graph.verifierSha256===verifierHash &&
    graph.ciSha256===ciHash,
    'Graph event hashes differ from authenticated model/verifier/CI artifacts');
  // Check the PR HEAD again, since CI and AI review may take a few minutes.
  invariant(gh(`repos/${REPO}/pulls/${prNumber}`).head.sha===head,
    'PR HEAD advanced while protected evidence was generated');
  const unsigned = { schemaVersion:3,status:'PASS',sourceDigest:source,
    testedCommit:head,ciRunId:ciRunId,graphEventId:graph.graphEventId,
    graphEventHash:graph.graphEventHash,unresolvedCritical:0,unresolvedHigh:0,
    critic:{sha256:criticHash},verifier:{sha256:verifierHash},ci:{sha256:ciHash},
    review:{method:'protected-granite-owner-v1',reviewerType:'automated-model-critic',
      humanIndependent:false,model:'ibm/granite3.3:2b',
      modelVerdict,codexReviewCommentId,
      modelDigest:model.provenance.modelDigest,commitSha:head,
      workflowRunId:model.run.id,
      trustedWorkflowCommit:protectedSha,
      artifactDigestSha256:model.provenance.artifactDigestSha256},
    ownerAuthorization:owner };
  const signed=signApproval(unsigned,process.env.LUMA_RELEASE_ATTESTATION_PRIVATE_KEY_B64);
  verifyApprovalSignature(signed,process.env.LUMA_RELEASE_ATTESTATION_PUBLIC_KEY_B64);
  save(directory,'release-approval.json',signed);
  verifyReview(directory); // Real Ed25519, Graph hash-chain and source replay.
  const files = [
    'graph-harness.events.jsonl',
    'evidence/cicd-enterprise/granite-review.json',
    'evidence/cicd-enterprise/independent-review.json',
    'evidence/cicd-enterprise/release-ci.json',
    'evidence/cicd-enterprise/release-approval.json',
  ];
  const bundle=resolve(ROOT,'release-bundle');
  for (const file of files) {
    const from=resolve(directory,file),to=resolve(bundle,file);
    mkdirSync(resolve(to,'..'),{recursive:true});copyFileSync(from,to);
  }
  writeFileSync(join(bundle,'manifest.json'),JSON.stringify({schemaVersion:3,
    status:'SIGNED',testedCommit:head,sourceDigest:source,
    files:Object.fromEntries(files.map(f=>[f,sha(resolve(bundle,f))])),
    ciRunId,modelReviewRunId:model.run.id,ownerCommentId:owner.commentId,
    signerPolicyCommit:protectedSha,graphHarnessPinnedCommit:trustedGraph,
    modelVerdict,codexReviewCommentId,
  },null,2)+'\n');
  console.log(JSON.stringify({status:'PROTECTED_V3_BUNDLE_SIGNED',pr:prNumber,
    sourceSha:head,sourceDigest:source,graphEventId:graph.graphEventId,
    bundleFiles:files,modelReviewRunId:model.run.id,ciRunId,ownerCommentId:owner.commentId,
    modelVerdict,codexReviewCommentId}));
  return signed;
}

if(process.argv[1]?.endsWith('/protected-solo-signer.mjs')){
  const [candidate,number]=process.argv.slice(2);
  const prNumber=Number(number),ciRunId=Number(process.env.LUMA_SOLO_CI_RUN_ID);
  signProtectedSoloRelease({directory:resolve(candidate||'.'),prNumber,ciRunId})
    .catch(error=>{console.error('PROTECTED_SOLO_V3_SIGN_BLOCKED: '+error.message);process.exitCode=1;});
}
