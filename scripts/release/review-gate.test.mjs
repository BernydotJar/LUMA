import { test } from 'vitest';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { assertReviewAttestation, reviewedSourceDigest, verifyReview } from './review-gate.mjs';
const digest = 'a'.repeat(64);
const approval = { schemaVersion: 2, status: 'PASS', sourceDigest: digest,
  testedCommit: 'e'.repeat(40), ciRunId: '39342438406',
  unresolvedCritical: 0, unresolvedHigh: 0, graphEventId: 'event-1', graphEventHash: 'b'.repeat(64),
  critic: { sha256: 'c'.repeat(64) }, verifier: { sha256: 'd'.repeat(64) },
  review: { method:'github-codex-clean-review', reviewer:'chatgpt-codex-connector[bot]',
    reviewId: 12345678, commitSha:'e'.repeat(40) } };
test('accepts a complete source-bound independent approval', () => assert.doesNotThrow(() => assertReviewAttestation(approval, digest)));
test('rejects missing, blocked, stale, or incomplete approvals', () => {
  for (const value of [null, { ...approval, status: 'BLOCKED' }, { ...approval, sourceDigest: 'e'.repeat(64) }, { ...approval, graphEventHash: null }, { ...approval, critic: null }, { ...approval, verifier: null }, { ...approval, schemaVersion: 1 },
    { ...approval, review: null }, { ...approval, review: { ...approval.review, commitSha:'f'.repeat(40) } }]) assert.throws(() => assertReviewAttestation(value, digest));
});
test('never approves unresolved critical or high findings', () => {
  assert.throws(() => assertReviewAttestation({ ...approval, unresolvedCritical: 1 }, digest));
  assert.throws(() => assertReviewAttestation({ ...approval, unresolvedHigh: 1 }, digest));
});
test('source digest catches code drift but ignores regenerated version metadata', () => {
  const root = mkdtempSync(join(tmpdir(), 'luma-review-test-'));
  try {
    execFileSync('git', ['init', '--quiet'], { cwd: root });
    mkdirSync(join(root, 'src/generated'), { recursive: true });
    writeFileSync(join(root, 'src/app.ts'), 'export const answer = 1;');
    writeFileSync(join(root, 'src/generated/release-manifest.json'), '{}');
    const first = reviewedSourceDigest(root);
    writeFileSync(join(root, 'src/generated/release-manifest.json'), '{"gitSha":"metadata"}');
    assert.equal(reviewedSourceDigest(root), first);
    writeFileSync(join(root, 'src/app.ts'), 'export const answer = 2;');
    assert.notEqual(reviewedSourceDigest(root), first);
    symlinkSync('app.ts', join(root, 'src/link.ts'));
    assert.throws(() => reviewedSourceDigest(root), /Non-regular release input/);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
test('absence of a Graph release approval blocks deployment', () => {
  const root = mkdtempSync(join(tmpdir(), 'luma-no-review-'));
  try { assert.throws(() => verifyReview(root)); }
  finally { rmSync(root, { recursive: true, force: true }); }
});


test('release digest ignores untracked Python bytecode while rejecting changed source', () => {
  const root = mkdtempSync(join(tmpdir(), 'luma-bytecode-review-'));
  try {
    execFileSync('git', ['init', '--quiet'], { cwd: root });
    writeFileSync(join(root, '.gitignore'), '__pycache__/\n*.py[cod]\n');
    mkdirSync(join(root, 'scripts/release'), { recursive: true });
    const source = join(root, 'scripts/release/quality_run.py');
    writeFileSync(source, 'REQUIRED = ("security",)\n');
    const first = reviewedSourceDigest(root);
    mkdirSync(join(root, 'scripts/release/__pycache__'));
    writeFileSync(join(root, 'scripts/release/__pycache__/quality_run.cpython-311.pyc'), 'generated bytes');
    assert.equal(reviewedSourceDigest(root), first, 'Generated Python caches must not change a reviewed source digest');
    writeFileSync(source, 'REQUIRED = ("security", "browser")\n');
    assert.notEqual(reviewedSourceDigest(root), first, 'Changing an actual source file must still invalidate the approval');
  } finally { rmSync(root, { recursive: true, force: true }); }
});

import { generateKeyPairSync } from 'node:crypto';
import { signApproval, verifyApprovalSignature } from './approval-signature.mjs';

test('only an external Ed25519 private key can authorize the exact source and Graph receipt', () => {
  const { privateKey, publicKey } = generateKeyPairSync('ed25519');
  const privateB64 = Buffer.from(privateKey.export({ format: 'pem', type: 'pkcs8' })).toString('base64');
  const publicB64 = Buffer.from(publicKey.export({ format: 'pem', type: 'spki' })).toString('base64');
  const unsigned = { ...approval, testedCommit: 'e'.repeat(40), ciRunId: '39342438406' };
  const signed = signApproval(unsigned, privateB64);
  assert.equal(verifyApprovalSignature(signed, publicB64), true);
  for (const patch of [
    { sourceDigest: 'f'.repeat(64) },
    { testedCommit: 'f'.repeat(40) },
    { graphEventHash: 'f'.repeat(64) },
    { ciRunId: '39342438407' },
    { critic: { sha256: 'f'.repeat(64) } },
    { review: { ...signed.review, reviewer:'BernydotJar' } },
    { review: { ...signed.review, reviewId: signed.review.reviewId + 1 } },
    { signature: { ...signed.signature, value: 'A'.repeat(86) + '==' } },
  ]) {
    assert.throws(() => verifyApprovalSignature({ ...signed, ...patch }, publicB64), /signature|Signature/i);
  }
  assert.throws(() => verifyApprovalSignature(signed, ''), /Trusted CI/);
  assert.throws(() => verifyApprovalSignature(unsigned, publicB64), /signature/i);
});

test('a PR-generated self-signature fails against the protected CI trust root', () => {
  const trusted = generateKeyPairSync('ed25519');
  const attacker = generateKeyPairSync('ed25519');
  const unsigned = { ...approval, testedCommit: 'e'.repeat(40), ciRunId: '39342438406' };
  const attackerSigned = signApproval(unsigned,
    Buffer.from(attacker.privateKey.export({ format: 'pem', type: 'pkcs8' })).toString('base64'));
  const protectedPublic = Buffer.from(trusted.publicKey.export({ format: 'pem', type: 'spki' })).toString('base64');
  assert.throws(() => verifyApprovalSignature(attackerSigned, protectedPublic), /signature/i);
});
